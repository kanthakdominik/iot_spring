-- =====================================================================
-- V1: initial schema (PostgreSQL 18 + TimescaleDB)
--   users          - application accounts
--   devices        - measuring devices (deviceId = MQTT client id = certificate CN)
--   routes         - measurement routes, one per (device, device_route_no)
--   measurements   - samples, TimescaleDB hypertable partitioned by time
--   route_markers  - points of interest inside a route
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS timescaledb;

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(50)  NOT NULL UNIQUE,
    password    VARCHAR(100) NOT NULL,
    role        VARCHAR(20)  NOT NULL
);

CREATE TABLE devices (
    id                VARCHAR(32)  PRIMARY KEY,
    name              VARCHAR(100) NOT NULL,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_seen_at      TIMESTAMPTZ,
    online            BOOLEAN      NOT NULL DEFAULT false,
    fw_version        VARCHAR(32),
    current_route_no  INTEGER,
    last_reset        VARCHAR(32),
    battery_mv        INTEGER,
    battery_pct       INTEGER,
    battery_at        TIMESTAMPTZ
);

CREATE TABLE routes (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id        VARCHAR(32)  NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    device_route_no  INTEGER      NOT NULL,
    name             VARCHAR(100) NOT NULL,
    description      VARCHAR(2000),
    started_at       TIMESTAMPTZ,
    ended_at         TIMESTAMPTZ,
    sample_count     INTEGER      NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_routes_device_route UNIQUE (device_id, device_route_no)
);

CREATE INDEX idx_routes_started_at ON routes (started_at DESC);

-- plain sequence instead of an identity column (works on every TimescaleDB version)
CREATE SEQUENCE measurements_id_seq;

CREATE TABLE measurements (
    id           BIGINT           NOT NULL DEFAULT nextval('measurements_id_seq'),
    route_id     BIGINT           NOT NULL REFERENCES routes (id) ON DELETE CASCADE,
    ts           TIMESTAMPTZ      NOT NULL,
    seq          INTEGER          NOT NULL,
    time_source  VARCHAR(4)       NOT NULL,
    gps_fix      BOOLEAN          NOT NULL,
    latitude     DOUBLE PRECISION,
    longitude    DOUBLE PRECISION,
    satellites   SMALLINT,
    hdop         REAL,
    speed        REAL,
    cps          INTEGER          NOT NULL,
    cpm          INTEGER          NOT NULL,
    usv_per_hr   DOUBLE PRECISION NOT NULL,
    mode         VARCHAR(8)       NOT NULL,
    -- on a hypertable every unique constraint must contain the partitioning column (ts)
    CONSTRAINT pk_measurements PRIMARY KEY (id, ts),
    CONSTRAINT uq_measurements_route_seq UNIQUE (route_id, seq, ts),
    CONSTRAINT ck_measurements_position CHECK (NOT gps_fix OR (latitude IS NOT NULL AND longitude IS NOT NULL))
);

-- automatic time partitioning (7-day chunks) instead of manual per-route partitions
SELECT create_hypertable('measurements', by_range('ts', INTERVAL '7 days'));

ALTER SEQUENCE measurements_id_seq OWNED BY measurements.id;

CREATE INDEX idx_measurements_route_ts ON measurements (route_id, ts);

CREATE TABLE route_markers (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id   BIGINT       NOT NULL REFERENCES routes (id) ON DELETE CASCADE,
    ts         TIMESTAMPTZ  NOT NULL,
    latitude   DOUBLE PRECISION,
    longitude  DOUBLE PRECISION,
    label      VARCHAR(200) NOT NULL,
    source     VARCHAR(10)  NOT NULL,   -- 'device' or 'user'
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_route_markers_route ON route_markers (route_id, ts);
