--   users          - preferences, created_at, roles ADMIN / VIEWER
--   devices        - GSM signal quality
--   routes         - statistics computed by RouteStatsJob, share token
--   device_health  - battery / signal history
--   device_events  - event log
--   alert_rules    - alert rules (+ 3 default rules)
--   alerts         - raised alerts
-- =====================================================================

-- ---------- users ----------
ALTER TABLE users ADD COLUMN preferences JSONB       NOT NULL DEFAULT '{}'::jsonb;
ALTER TABLE users ADD COLUMN created_at  TIMESTAMPTZ NOT NULL DEFAULT now();
-- roles of the master's thesis (e.g. USER) become VIEWER; ROLE_ prefixed names are normalised
UPDATE users SET role = CASE WHEN upper(role) IN ('ADMIN', 'ROLE_ADMIN') THEN 'ADMIN' ELSE 'VIEWER' END
WHERE role NOT IN ('ADMIN', 'VIEWER');
ALTER TABLE users ADD CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'VIEWER'));

-- ---------- devices: GSM signal quality ----------
ALTER TABLE devices ADD COLUMN signal_csq SMALLINT;          -- 0..31, NULL = unknown (99 from the modem -> NULL)
ALTER TABLE devices ADD COLUMN signal_at  TIMESTAMPTZ;

-- ---------- routes: statistics (RouteStatsJob) and sharing ----------
ALTER TABLE routes ADD COLUMN fix_count   INTEGER NOT NULL DEFAULT 0;
ALTER TABLE routes ADD COLUMN distance_m  DOUBLE PRECISION;
ALTER TABLE routes ADD COLUMN min_usv     DOUBLE PRECISION;
ALTER TABLE routes ADD COLUMN avg_usv     DOUBLE PRECISION;
ALTER TABLE routes ADD COLUMN max_usv     DOUBLE PRECISION;
ALTER TABLE routes ADD COLUMN dose_usv    DOUBLE PRECISION;
ALTER TABLE routes ADD COLUMN preview     JSONB;             -- {"track":[[lat,lon,usv],...],"spark":[usv,...]}
-- DEFAULT true: every existing route (e.g. imported from the thesis) is recomputed after the start
ALTER TABLE routes ADD COLUMN stats_dirty BOOLEAN NOT NULL DEFAULT true;
ALTER TABLE routes ADD COLUMN share_token VARCHAR(32) UNIQUE;
CREATE INDEX idx_routes_stats_dirty ON routes (id) WHERE stats_dirty;
CREATE INDEX idx_routes_device_started ON routes (device_id, started_at DESC);

-- ---------- battery / signal history ----------
CREATE TABLE device_health (
    device_id    VARCHAR(32) NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    ts           TIMESTAMPTZ NOT NULL,
    battery_mv   INTEGER,
    battery_pct  INTEGER,
    signal_csq   SMALLINT,
    PRIMARY KEY (device_id, ts)
);

-- ---------- event log ----------
CREATE TABLE device_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id  VARCHAR(32)  REFERENCES devices (id) ON DELETE CASCADE,   -- NULL = system event
    route_id   BIGINT       REFERENCES routes (id) ON DELETE SET NULL,
    ts         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    type       VARCHAR(24)  NOT NULL,
    severity   VARCHAR(8)   NOT NULL DEFAULT 'INFO',                     -- INFO | WARN | ERROR
    message    VARCHAR(500) NOT NULL,
    data       JSONB
);
CREATE INDEX idx_device_events_ts ON device_events (ts DESC);
CREATE INDEX idx_device_events_device_ts ON device_events (device_id, ts DESC);

-- ---------- alerts ----------
CREATE TABLE alert_rules (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100) NOT NULL,
    type             VARCHAR(24)  NOT NULL CHECK (type IN ('DOSE_RATE_ABOVE', 'BATTERY_BELOW', 'DEVICE_OFFLINE')),
    threshold        DOUBLE PRECISION,                                      -- uSv/h or %; NULL for DEVICE_OFFLINE
    device_id        VARCHAR(32) REFERENCES devices (id) ON DELETE CASCADE, -- NULL = all devices
    enabled          BOOLEAN NOT NULL DEFAULT true,
    cooldown_minutes INTEGER NOT NULL DEFAULT 15,
    notify_push      BOOLEAN NOT NULL DEFAULT true,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE alerts (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id          BIGINT REFERENCES alert_rules (id) ON DELETE SET NULL,
    rule_name        VARCHAR(100) NOT NULL,
    type             VARCHAR(24)  NOT NULL,
    device_id        VARCHAR(32)  REFERENCES devices (id) ON DELETE CASCADE,
    route_id         BIGINT       REFERENCES routes (id) ON DELETE SET NULL,
    ts               TIMESTAMPTZ  NOT NULL,
    value            DOUBLE PRECISION,
    threshold        DOUBLE PRECISION,
    latitude         DOUBLE PRECISION,
    longitude        DOUBLE PRECISION,
    message          VARCHAR(300) NOT NULL,
    acknowledged_at  TIMESTAMPTZ,
    acknowledged_by  VARCHAR(50)
);
CREATE INDEX idx_alerts_ts ON alerts (ts DESC);
CREATE INDEX idx_alerts_open ON alerts (ts DESC) WHERE acknowledged_at IS NULL;
CREATE INDEX idx_alerts_rule_device ON alerts (rule_id, device_id, ts DESC);

