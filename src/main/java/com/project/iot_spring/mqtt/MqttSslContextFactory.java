package com.project.iot_spring.mqtt;

import org.bouncycastle.asn1.pkcs.PrivateKeyInfo;
import org.bouncycastle.jce.provider.BouncyCastleProvider;
import org.bouncycastle.openssl.PEMKeyPair;
import org.bouncycastle.openssl.PEMParser;
import org.bouncycastle.openssl.jcajce.JcaPEMKeyConverter;

import javax.net.ssl.KeyManagerFactory;
import javax.net.ssl.SSLContext;
import javax.net.ssl.TrustManagerFactory;
import java.io.FileNotFoundException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.KeyStore;
import java.security.PrivateKey;
import java.security.SecureRandom;
import java.security.Security;
import java.security.cert.Certificate;
import java.security.cert.CertificateFactory;

/**
 * Builds the TLS context for the broker connection from PEM files:
 * {@code ca-cert.pem}, {@code client-cert.pem}, {@code client-key.pem} (PKCS#1 or PKCS#8),
 * generated by deploy/scripts/gen-certs.sh.
 */
final class MqttSslContextFactory {

    private static final char[] NO_PASSWORD = new char[0];

    static {
        if (Security.getProvider(BouncyCastleProvider.PROVIDER_NAME) == null) {
            Security.addProvider(new BouncyCastleProvider());
        }
    }

    private MqttSslContextFactory() {
    }

    static SSLContext create(String certDir) throws Exception {
        Certificate caCert = loadCertificate(certDir, "ca-cert.pem");
        Certificate clientCert = loadCertificate(certDir, "client-cert.pem");
        PrivateKey privateKey = loadPrivateKey(certDir, "client-key.pem");

        KeyStore trustStore = KeyStore.getInstance(KeyStore.getDefaultType());
        trustStore.load(null, null);
        trustStore.setCertificateEntry("ca", caCert);
        TrustManagerFactory tmf = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm());
        tmf.init(trustStore);

        KeyStore keyStore = KeyStore.getInstance(KeyStore.getDefaultType());
        keyStore.load(null, null);
        keyStore.setKeyEntry("client", privateKey, NO_PASSWORD, new Certificate[]{clientCert});
        KeyManagerFactory kmf = KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm());
        kmf.init(keyStore, NO_PASSWORD);

        SSLContext sslContext = SSLContext.getInstance("TLS");
        sslContext.init(kmf.getKeyManagers(), tmf.getTrustManagers(), new SecureRandom());
        return sslContext;
    }

    private static InputStream open(String certDir, String fileName) throws Exception {
        if (certDir == null || certDir.isBlank()) {
            throw new IllegalStateException("mqtt.cert-dir is not set");
        }
        Path path = Path.of(certDir, fileName);
        if (!Files.exists(path)) {
            throw new FileNotFoundException("Certificate file not found: " + path);
        }
        return Files.newInputStream(path);
    }

    private static Certificate loadCertificate(String certDir, String fileName) throws Exception {
        try (InputStream is = open(certDir, fileName)) {
            return CertificateFactory.getInstance("X.509").generateCertificate(is);
        }
    }

    private static PrivateKey loadPrivateKey(String certDir, String fileName) throws Exception {
        try (Reader reader = new InputStreamReader(open(certDir, fileName), StandardCharsets.US_ASCII);
             PEMParser pemParser = new PEMParser(reader)) {
            Object object = pemParser.readObject();
            JcaPEMKeyConverter converter = new JcaPEMKeyConverter();
            if (object instanceof PEMKeyPair keyPair) {          // "BEGIN RSA PRIVATE KEY" (PKCS#1)
                return converter.getPrivateKey(keyPair.getPrivateKeyInfo());
            }
            if (object instanceof PrivateKeyInfo keyInfo) {      // "BEGIN PRIVATE KEY" (PKCS#8)
                return converter.getPrivateKey(keyInfo);
            }
            throw new IllegalArgumentException("Unsupported private key format in " + fileName);
        }
    }
}
