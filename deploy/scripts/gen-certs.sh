#!/usr/bin/env bash
# Generates the private CA and all TLS certificates for MQTT.
#
#   ./scripts/gen-certs.sh             -> CA + broker + backend + device "esp32-1"
#   ./scripts/gen-certs.sh esp32-2     -> additionally a certificate for another device
#
# Existing files are never overwritten (delete them yourself to regenerate).
# Result (deploy/certs/, NOT committed to git):
#   ca/          ca.key (keep it secret!), ca.crt
#   mosquitto/   ca.crt, server.crt, server.key       -> mounted into mosquitto
#   backend/     ca-cert.pem, client-cert.pem, client-key.pem -> mounted into backend
#   <device>/    ca.crt, client.crt, client.key, secrets_certs.h -> paste into ESP32 secrets.h
set -euo pipefail

cd "$(dirname "$0")/.."
[ -f .env ] && set -a && . ./.env && set +a
DOMAIN="${DOMAIN:?DOMAIN is not set - fill deploy/.env first}"
DEVICE="${1:-esp32-1}"
DAYS=3650
C=certs

mkdir -p "$C/ca" "$C/mosquitto" "$C/backend" "$C/$DEVICE"
chmod 755 "$C" "$C/mosquitto" "$C/backend"
chmod 700 "$C/ca"

# ---------- CA ----------
if [ ! -f "$C/ca/ca.key" ]; then
    echo ">>> Creating CA"
    openssl genrsa -out "$C/ca/ca.key" 4096
    openssl req -x509 -new -key "$C/ca/ca.key" -sha256 -days "$DAYS" \
        -subj "/CN=IoT Radiation CA" -out "$C/ca/ca.crt"
    chmod 600 "$C/ca/ca.key"
fi

# sign <dir> <name> <CN> <extfile-content>
sign() {
    local dir=$1 name=$2 cn=$3 ext=$4
    # -traditional => "BEGIN RSA PRIVATE KEY" (PKCS#1), required by the backend loader and ESP32 code
    openssl genrsa -traditional -out "$dir/$name.key" 2048
    openssl req -new -key "$dir/$name.key" -subj "/CN=$cn" -out "$dir/$name.csr"
    printf '%b' "$ext" > "$dir/$name.ext"
    openssl x509 -req -in "$dir/$name.csr" -CA "$C/ca/ca.crt" -CAkey "$C/ca/ca.key" \
        -CAcreateserial -days "$DAYS" -sha256 -extfile "$dir/$name.ext" -out "$dir/$name.crt"
    rm -f "$dir/$name.csr" "$dir/$name.ext"
}

# ---------- Broker (server) ----------
if [ ! -f "$C/mosquitto/server.crt" ]; then
    echo ">>> Creating broker certificate for $DOMAIN"
    sign "$C/mosquitto" server "$DOMAIN" \
        "basicConstraints=CA:FALSE\nkeyUsage=digitalSignature,keyEncipherment\nextendedKeyUsage=serverAuth\nsubjectAltName=DNS:$DOMAIN,DNS:mosquitto,DNS:localhost"
    cp "$C/ca/ca.crt" "$C/mosquitto/ca.crt"
    # mosquitto runs as uid 1883 inside the container and must be able to read the key
    chmod 644 "$C/mosquitto/"*
fi

CLIENT_EXT="basicConstraints=CA:FALSE\nkeyUsage=digitalSignature,keyEncipherment\nextendedKeyUsage=clientAuth"

# ---------- Backend client ----------
if [ ! -f "$C/backend/client-cert.pem" ]; then
    echo ">>> Creating backend client certificate"
    sign "$C/backend" client iot_spring "$CLIENT_EXT"
    mv "$C/backend/client.crt" "$C/backend/client-cert.pem"
    mv "$C/backend/client.key" "$C/backend/client-key.pem"
    cp "$C/ca/ca.crt" "$C/backend/ca-cert.pem"
    # backend container runs as a non-root user
    chmod 644 "$C/backend/"*
fi

# ---------- Device client ----------
if [ ! -f "$C/$DEVICE/client.crt" ]; then
    echo ">>> Creating device certificate: $DEVICE"
    sign "$C/$DEVICE" client "$DEVICE" "$CLIENT_EXT"
    cp "$C/ca/ca.crt" "$C/$DEVICE/ca.crt"
    chmod 600 "$C/$DEVICE/client.key"

    # Ready-to-paste block for iot_esp32/secrets.h
    {
        echo "// ---- generated by gen-certs.sh for device: $DEVICE ----"
        echo "// const char *broker = \"$DOMAIN\";"
        echo "// const int brokerPort = 8883;"
        echo
        echo "static const char AWS_CERT_CA[] PROGMEM = R\"EOF("
        cat "$C/$DEVICE/ca.crt"
        echo ")EOF\";"
        echo
        echo "static const char AWS_CERT_CRT[] PROGMEM = R\"KEY("
        cat "$C/$DEVICE/client.crt"
        echo ")KEY\";"
        echo
        echo "static const char AWS_CERT_PRIVATE[] PROGMEM = R\"KEY("
        cat "$C/$DEVICE/client.key"
        echo ")KEY\";"
    } > "$C/$DEVICE/secrets_certs.h"
    chmod 600 "$C/$DEVICE/secrets_certs.h"
fi

echo
echo "Done. Certificates are in deploy/$C/"
echo "ESP32 block to paste into secrets.h: deploy/$C/$DEVICE/secrets_certs.h"
